import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
const PORT = 5194, PEER = 9001, BUILD = '/tmp/ravenswood-test-build';
const procs = [spawn('npx', ['peerjs', '--port', String(PEER), '--path', '/', '--host', '127.0.0.1'], { stdio: 'ignore' }), spawn('npx', ['vite', 'preview', '--outDir', BUILD, '--port', String(PORT), '--strictPort'], { stdio: 'ignore' })];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 100; i++) { try { if ((await fetch(`http://localhost:${PORT}/`)).ok && (await fetch(`http://127.0.0.1:${PEER}/`)).status < 500) break; } catch {} await sleep(300); }
const FLAGS = `peer=127.0.0.1:${PEER}&debug&fx=low&fps=10`;
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const st = await browser.newPage({ viewport: { width: 1100, height: 640 } });
await st.goto(`http://localhost:${PORT}/?st&${FLAGS}`);
await st.waitForFunction(() => window.__host && window.__hostNet?.getState().status === 'open', null, { timeout: 90000 });
const room = await st.evaluate(() => window.__host.getState().g.room);
const p = await browser.newPage({ viewport: { width: 1100, height: 640 } });
p.on('request', (r) => r.isNavigationRequest() && console.log('[P1 NAV REQUEST]', r.method(), r.url(), r.frame() === p.mainFrame() ? 'main' : 'sub'));
p.on('framenavigated', (f) => console.log('[P1 framenavigated]', f.url()));
await p.addInitScript(() => {
  window.addEventListener('submit', (e) => console.log('SUBMIT capture target=' + e.target.className), true);
  window.addEventListener('submit', (e) => console.log('SUBMIT bubble prevented=' + e.defaultPrevented), false);
  window.addEventListener('pagehide', () => console.log('PAGEHIDE'));
  window.addEventListener('beforeunload', () => console.log('BEFOREUNLOAD'));
  const r = location.reload.bind(location);
  location.reload = (...a) => { console.log('RELOAD CALLED ' + new Error().stack); return r(...a); };
});
p.on('console', (m) => /SUBMIT|PAGEHIDE|BEFOREUNLOAD|RELOAD/.test(m.text()) && console.log('[P1 log]', m.text().slice(0, 400)));
p.on('console', (m) => (m.type() === 'warning' || m.type() === 'error') && !/satellite|nostr|tunnel/.test(m.text()) && console.log('[P1]', m.text().slice(0, 200)));
p.on('pageerror', (e) => console.log('[P1 pageerror]', e.message));
await p.goto(`http://localhost:${PORT}/?room=${room}&${FLAGS}`);
await p.waitForSelector('.join-name input', { timeout: 180000 });
await sleep(500);
await p.fill('.join-name input', 'Abbey');
await sleep(300);
await p.click('.join-name button', { noWaitAfter: true, timeout: 15000 });
await sleep(4000);
console.log('url now', p.url(), 'nav type', await p.evaluate(() => performance.getEntriesByType('navigation')[0]?.type).catch((e) => e.message));
await p.waitForSelector('.join-animal', { timeout: 20000 });
await sleep(6000);
console.log('stage html:', await p.evaluate(() => document.querySelector('.join-stage')?.innerHTML.slice(0, 600)));
console.log('canvases:', await p.evaluate(() => [...document.querySelectorAll('canvas')].map((c) => `${c.className || '(none)'} ${c.width}x${c.height} ctx:${Boolean(c.getContext('webgl2') || c.getContext('webgl'))} lost:${(c.getContext('webgl2') || c.getContext('webgl'))?.isContextLost()}`)));
await p.screenshot({ path: '/tmp/claude-0/stage-diag.png' });
await browser.close();
for (const pr of procs) pr.kill();
