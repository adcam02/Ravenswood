/** A prompt for tonight that hasn't come up yet in this run of nights (any, once they've all had a turn). */
export function pickPrompt(used: string[], seed = Math.random()): string {
  const fresh = PROMPTS.filter((p) => !used.includes(p));
  const list = fresh.length ? fresh : PROMPTS;
  return list[Math.floor(seed * list.length) % list.length];
}

/** A few different prompts to choose between tonight, none of them used lately (if there are enough). */
export function pickPrompts(used: string[], n: number): string[] {
  const fresh = PROMPTS.filter((p) => !used.includes(p));
  const pool = [...(fresh.length >= n ? fresh : PROMPTS)];
  const out: string[] = [];
  while (out.length < n && pool.length) out.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0]);
  return out;
}
